/**
 * Динамическая синхронизация каталога моделей с https://models.dev/api/v2/catalog.json
 * (точно как в packages/core/src/models-dev.ts в anomalyco/opencode)
 */
export async function syncModelsDevCatalog(existing: ModelInfo[]): Promise<{
  models: ModelInfo[]
  addedCount: number
  source: string
}> {
  const endpoints = [
    "/api/models-dev",
    "https://models.dev/api/v2/catalog.json",
    "https://models.dev/api.json",
  ]

  for (const url of endpoints) {
    try {
      const res = await fetch(url, {
        headers: { Accept: "application/json" },
      })
      if (!res.ok) continue
      const catalog = (await res.json()) as Record<string, any>
      if (!catalog || typeof catalog !== "object") continue

      const map = new Map<string, ModelInfo>()
      for (const m of existing) {
        map.set(`${m.providerID}:${m.id}`, m)
      }

      let addedCount = 0
      const opencodeProvider = catalog.opencode
      if (opencodeProvider && typeof opencodeProvider.models === "object") {
        for (const [mid, raw] of Object.entries<any>(opencodeProvider.models)) {
          if (!raw || typeof raw !== "object") continue
          const costIn = raw.cost?.text?.input?.price ?? raw.cost?.input ?? 0
          const costOut = raw.cost?.text?.output?.price ?? raw.cost?.output ?? 0
          const isFree = costIn === 0 && costOut === 0
          const key = `opencode:${mid}`
          if (!map.has(key)) {
            const apis = raw.api ? Object.keys(raw.api) : ["chat-completions"]
            const firstProtocol = (apis[0] ?? "chat-completions") as ApiProtocol
            const baseURL =
              raw.api?.[firstProtocol]?.base_url ??
              (firstProtocol === "messages"
                ? "https://opencode.ai/inference/anthropic/v1"
                : "https://opencode.ai/inference/openai/v1")

            map.set(key, {
              id: mid,
              providerID: "opencode",
              name: `${raw.name ?? mid}${isFree ? " (OpenCode Zen Free)" : ""}`,
              family: raw.family,
              free: isFree,
              status: raw.status === "deprecated" ? "deprecated" : "active",
              type: raw.type === "decision" ? "decision" : "chat",
              protocol: firstProtocol,
              baseURL,
              contextLimit: raw.limit?.context ?? 200000,
              outputLimit: raw.limit?.output ?? 32000,
              costInput: costIn,
              costOutput: costOut,
              capabilities: {
                tools: Boolean(raw.capabilities?.tools?.supported ?? true),
                reasoning: Boolean(raw.capabilities?.reasoning?.supported ?? false),
                reasoningEffort: Array.isArray(raw.capabilities?.reasoning?.effort)
                  ? raw.capabilities.reasoning.effort
                  : undefined,
                vision: Array.isArray(raw.modalities?.input) && raw.modalities.input.includes("image"),
              },
              description: `Синхронизировано из models.dev (${isFree ? "Бесплатная модель $0" : `$${costIn}/M in`})`,
            })
            addedCount++
          }
        }
      }

      return {
        models: Array.from(map.values()),
        addedCount,
        source: url,
      }
    } catch {
      // try next endpoint
    }
  }

  return {
    models: existing,
    addedCount: 0,
    source: "builtin-snapshot",
  }
}
